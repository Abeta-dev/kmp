#!/usr/bin/env bash
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
TAG="v0.1.0"
REPO="Abeta-dev/kmp"
OUT_DIR=""
SWIFT_VERSION="5.9"

usage() {
  echo "Usage: $0 [--tag v0.1.0] [--repo Abeta-dev/kmp] [--out-dir dist/xcframeworks] [--swift-version 5.9]" >&2
}

while [[ $# -gt 0 ]]; do
  case "$1" in
    --tag)
      if [[ $# -lt 2 || -z "${2:-}" ]]; then
        echo "ERROR: --tag requires a non-empty value." >&2
        usage
        exit 2
      fi
      TAG="$2"
      shift 2
      ;;
    --repo)
      if [[ $# -lt 2 || -z "${2:-}" ]]; then
        echo "ERROR: --repo requires a non-empty value." >&2
        usage
        exit 2
      fi
      REPO="$2"
      shift 2
      ;;
    --out-dir)
      if [[ $# -lt 2 || -z "${2:-}" ]]; then
        echo "ERROR: --out-dir requires a non-empty value." >&2
        usage
        exit 2
      fi
      OUT_DIR="$2"
      shift 2
      ;;
    --swift-version)
      if [[ $# -lt 2 || -z "${2:-}" ]]; then
        echo "ERROR: --swift-version requires a non-empty value." >&2
        usage
        exit 2
      fi
      SWIFT_VERSION="$2"
      shift 2
      ;;
    -h|--help)
      usage
      exit 0
      ;;
    *)
      echo "ERROR: Unknown argument: $1" >&2
      usage
      exit 2
      ;;
  esac
done

if [[ -z "$OUT_DIR" ]]; then
  OUT_DIR="${ROOT_DIR}/dist/xcframeworks"
fi

find_xcframework() {
  local module="$1"
  local name="$2"
  local candidate
  for candidate in \
    "${ROOT_DIR}/kmp/${module}/build/XCFrameworks/release/${name}.xcframework" \
    "${ROOT_DIR}/kmp/.build.nosync/${module}/XCFrameworks/release/${name}.xcframework"; do
    if [[ -d "$candidate" ]]; then
      echo "$candidate"
      return 0
    fi
  done
  echo "ERROR: Missing Release XCFramework ${name}.xcframework for module :${module}." >&2
  echo "Run: (cd kmp && ./gradlew :${module}:assemble${name}ReleaseXCFramework --max-workers=1 --no-daemon)" >&2
  exit 1
}

zip_xcframework() {
  local src_dir="$1"
  local dest_zip="$2"
  rm -f "$dest_zip"
  if command -v ditto >/dev/null 2>&1; then
    ditto -c -k --sequesterRsrc --keepParent "$src_dir" "$dest_zip"
  else
    local parent base
    parent="$(dirname "$src_dir")"
    base="$(basename "$src_dir")"
    (cd "$parent" && zip -qry "$dest_zip" "$base")
  fi
}

compute_sha256() {
  local file="$1"
  local abs_file checksum
  abs_file="$(cd "$(dirname "$file")" && pwd)/$(basename "$file")"

  # Run `swift package compute-checksum` inside an isolated temp directory so
  # SwiftPM never creates a stray `.build/` directory in the workspace root.
  if command -v swift >/dev/null 2>&1; then
    local tmp_dir rc=0
    tmp_dir="$(mktemp -d)"
    checksum="$(cd "$tmp_dir" && swift package compute-checksum "$abs_file")" || rc=$?
    rm -rf "$tmp_dir"
    if [[ "$rc" -ne 0 ]]; then
      echo "ERROR: swift package compute-checksum failed for ${abs_file}" >&2
      return "$rc"
    fi
  elif command -v shasum >/dev/null 2>&1; then
    checksum="$(shasum -a 256 "$abs_file" | awk '{print $1}')"
  else
    checksum="$(sha256sum "$abs_file" | awk '{print $1}')"
  fi

  checksum="$(printf '%s' "$checksum" | tr '[:upper:]' '[:lower:]')"
  if [[ ! "$checksum" =~ ^[0-9a-f]{64}$ ]]; then
    echo "ERROR: Invalid SHA-256 checksum computed for ${abs_file}: '${checksum}'" >&2
    return 1
  fi
  printf '%s\n' "$checksum"
}

SDUI_XCF="$(find_xcframework "sdui-layout" "AbetaSduiKit")"
WATCH_XCF="$(find_xcframework "watch-companion" "AbetaWatchKit")"

mkdir -p "$OUT_DIR"
OUT_DIR="$(cd "$OUT_DIR" && pwd)"

SDUI_ZIP_NAME="AbetaSduiKit-${TAG}.xcframework.zip"
WATCH_ZIP_NAME="AbetaWatchKit-${TAG}.xcframework.zip"
SDUI_ZIP="${OUT_DIR}/${SDUI_ZIP_NAME}"
WATCH_ZIP="${OUT_DIR}/${WATCH_ZIP_NAME}"

echo "==> Packaging AbetaSduiKit.xcframework -> ${SDUI_ZIP}"
zip_xcframework "$SDUI_XCF" "$SDUI_ZIP"

echo "==> Packaging AbetaWatchKit.xcframework -> ${WATCH_ZIP}"
zip_xcframework "$WATCH_XCF" "$WATCH_ZIP"

SDUI_SHA="$(compute_sha256 "$SDUI_ZIP")"
WATCH_SHA="$(compute_sha256 "$WATCH_ZIP")"

cat > "${OUT_DIR}/SHA256SUMS.txt" <<EOF
${SDUI_SHA}  ${SDUI_ZIP_NAME}
${WATCH_SHA}  ${WATCH_ZIP_NAME}
EOF

SDUI_URL="https://github.com/${REPO}/releases/download/${TAG}/${SDUI_ZIP_NAME}"
WATCH_URL="https://github.com/${REPO}/releases/download/${TAG}/${WATCH_ZIP_NAME}"
SPM_VERSION="${TAG#v}"
SPM_MIRROR_REPO="${REPO}-spm"

cat > "${OUT_DIR}/Package.swift" <<EOF
// swift-tools-version: ${SWIFT_VERSION}
// Generated by scripts/package_xcframeworks.sh for ${REPO} ${TAG}
import PackageDescription

let package = Package(
    name: "AbetaKmpKit",
    platforms: [
        .iOS(.v15),
        .watchOS(.v9),
    ],
    products: [
        .library(
            name: "AbetaSduiKit",
            targets: ["AbetaSduiKit"]
        ),
        .library(
            name: "AbetaWatchKit",
            targets: ["AbetaWatchKit"]
        ),
    ],
    targets: [
        .binaryTarget(
            name: "AbetaSduiKit",
            url: "${SDUI_URL}",
            checksum: "${SDUI_SHA}"
        ),
        .binaryTarget(
            name: "AbetaWatchKit",
            url: "${WATCH_URL}",
            checksum: "${WATCH_SHA}"
        ),
    ]
)
EOF

echo "==> Generated SwiftPM artifacts in ${OUT_DIR}:"
ls -lh "${SDUI_ZIP}" "${WATCH_ZIP}" "${OUT_DIR}/SHA256SUMS.txt" "${OUT_DIR}/Package.swift"
cat <<EOF

==> SwiftPM Direct-URL Summary (${REPO} @ ${TAG}, swift-tools-version ${SWIFT_VERSION})
  AbetaSduiKit  (iOS/iPadOS 15+)
    URL:      ${SDUI_URL}
    SHA-256:  ${SDUI_SHA}
  AbetaWatchKit (watchOS 9+)
    URL:      ${WATCH_URL}
    SHA-256:  ${WATCH_SHA}

==> Xcode Swift Package Manager Instructions
  1. Upload ${SDUI_ZIP_NAME}, ${WATCH_ZIP_NAME}, SHA256SUMS.txt, and Package.swift to GitHub Release ${TAG} of ${REPO}.
  2. In Xcode -> File -> Add Package Dependencies..., enter:
       https://github.com/${SPM_MIRROR_REPO}
     and select version ${SPM_VERSION} (or copy ${OUT_DIR}/Package.swift into your SwiftPM repo).
  3. Link the binary products to your Apple targets:
       - iOS / iPadOS 15+ target: import AbetaSduiKit
       - watchOS 9+ target:       import AbetaWatchKit
  4. Verify manifest locally:
       ./scripts/verify_spm_package.sh "${OUT_DIR}/Package.swift" --expected-tag "${TAG}"
EOF
